#!/usr/bin/env bash
# Wave heights for one session under a list of processing combinations.
# Run: ./test_config.sh
#
# Writes <measurement>/test_config/<prefix>_test_config.csv (one row per combination
# and taper) and one table per taper, <prefix>_test_config_<f1>_<f2>.png, in the
# style of the met_waves tables. Columns: decimation (sample rate), FIR, Welch
# segment length, capture length, and Hs for Madgwick, Kalman, Kalman NXP and SFLP
# (tools/analysis/config_test.py).
#
# The first run reconstructs the session from the raw log once per (D, FIR) into
# test_config/work/ (a few minutes each); later runs reuse it. Delete work/ after a
# change in the reconstruction.
#
# DO NOT EDIT THIS FILE WHILE IT RUNS: bash reads it as it goes.

# ============================ settings ========================================

# The set in tools/analysis/session_sets.py, and the session in it.
SET=KATTEN
SESSION=20260830_131145

# One row per entry: "D FIR SEGLEN MINUTES [HZ [TAPS]]"
#   D        the raw stream averaged in blocks of D first (480/D Hz)
#   FIR      the decimation stages (raw -> 80 Hz rows -> Welch rate): average
#            (block/bucket mean) or sinc (the Hamming-windowed sinc FIR as on board)
#            for both, or S1/S2 for each stage on its own, with the taps written
#            into it: sinc31/sinc129, average/sinc129, sinc31/average
#            single<taps>: ONE FIR straight from the raw rate to the Welch rate
#            (no stage 2), e.g. single129. matched<n2>: the single stage that
#            matches a two-stage chain with n2 taps in stage 2 - M1(n2-1)+1 taps,
#            M1 = (480/D)/80: 769 / 385 / 193 at D1 / D2 / D4 for matched129,
#            181 / 91 / 47 for matched31
#   SEGLEN   Welch segment length (at 10 Hz: 1024 = 102.4 s, 512 = 51.2 s)
#   MINUTES  the capture cut after this many minutes
#   HZ       the Welch rate stage 2 decimates to; omitted = 10 Hz (as on board).
#            Halve SEGLEN with it to keep the segment duration (and df) the same.
#   TAPS     the FIR taps of every "sinc" without its own; omitted = the capture's own
#            (fir_ntap in cfg.csv - 129 here; the firmware has 31 since 2026-09-03)
# D = 8 (60 Hz) is left out: below the 80 Hz row rate the chain cannot run.
# The first entry is the reference in <prefix>_test_config_heatmap.png.
COMBOS=("1 sinc 1024 30"
        "2 sinc 1024 30"
        "4 sinc 1024 30"
        "1 sinc 512 30 5"
        "2 sinc 512 30 5"
        "4 sinc 512 30 5"
        "1 sinc 1024 30 10 31"
        "2 sinc 1024 30 10 31"
        "4 sinc 1024 30 10 31"
        "1 sinc 512 30 5 31"
        "2 sinc 512 30 5 31"
        "4 sinc 512 30 5 31"
        "1 sinc31/sinc129 1024 30"
        "2 sinc31/sinc129 1024 30"
        "4 sinc31/sinc129 1024 30"
        "1 sinc31/sinc129 512 30 5"
        "2 sinc31/sinc129 512 30 5"
        "4 sinc31/sinc129 512 30 5"
        "1 average/sinc129 1024 30"
        "2 average/sinc129 1024 30"
        "4 average/sinc129 1024 30"
        "1 average/sinc129 512 30 5"
        "2 average/sinc129 512 30 5"
        "4 average/sinc129 512 30 5"
        "1 sinc31/average 1024 30"
        "2 sinc31/average 1024 30"
        "4 sinc31/average 1024 30"
        "1 sinc31/average 512 30 5"
        "2 sinc31/average 512 30 5"
        "4 sinc31/average 512 30 5"
        "1 single129 1024 30"
        "2 single129 1024 30"
        "4 single129 1024 30"
        "1 single129 512 30 5"
        "2 single129 512 30 5"
        "4 single129 512 30 5"
        "1 matched129 1024 30"
        "1 matched129 512 30 5"
        "1 matched31 1024 30"
        "1 matched31 512 30 5"
        "1 average 1024 30"
        "2 average 1024 30"
        "4 average 1024 30"
        "1 average 512 30 5"
        "2 average 512 30 5"
        "4 average 512 30 5"
        "1 sinc 1024 25"
        "1 sinc 1024 20"
        "1 sinc 1024 15"
        "1 sinc 1024 10")

# One table per taper ("F1 F2" in Hz) - the configs of plot.sh but 0.03-0.05.
TAPERS=("0.05 0.1"
        "0.07 0.1"
        "0.1 0.15"
        "0.1 0.2")

# Combinations (from COMBOS) whose PSD (Madgwick) is drawn together: the untapered
# acceleration in <prefix>_test_config_psd_acc.png, the tapered elevation (PSD_TAPER)
# in <prefix>_test_config_psd_eta.png.
# Empty = no figure.
PSD_COMPARE=("1 average 1024 30"
             "1 sinc 1024 30")
# The taper for the PSD figures' legends, the fmax table and the heatmaps - one
# of TAPERS.
PSD_TAPER="0.05 0.1"

# Decimation chains (the FIR field of COMBOS, with TAPS if any) as rows in
# <prefix>_test_config_chains_madgwick_<f1>_<f2>_<f>Hz.png (+ .csv): Hs and Tz (Madgwick, PSD_TAPER)
# per Welch rate at D1, from the saved PSDs. Empty = no table.
CHAIN_TABLE=("matched129"
             "sinc"
             "single129"
             "matched31"
             "sinc 31"
             "sinc31/sinc129")
# Upper integration limits [Hz] for the chain table: one table each,
# <prefix>_test_config_chains_madgwick_<f1>_<f2>_<f>Hz.png, computed from the saved PSDs.
CHAIN_FMAX=(1 2)

# Combinations without D ("FIR SEGLEN MINUTES [HZ [TAPS]]"): Hs and Tp per AHRS filter at
# every D of it in COMBOS (PSD_TAPER), one table each,
# <prefix>_test_config_decimation_<fir>_<hz>Hz_<seglen>_<f1>_<f2>.png (+ .csv).
# Empty = no table.
DECIMATION_TABLE=("sinc 1024 30")

# Upper integration limits [Hz] for <prefix>_test_config_fmax.png (+ .csv): Hs
# (Madgwick, PSD_TAPER) of the PSD_COMPARE combinations integrated to each, from
# the saved PSDs. Empty = no table.
FMAX_COMPARE=(1 2 5)

# Upper frequency [Hz] for Hs, as in plot.sh. Empty = no limit of its own.
WAVE_PARAM_FMAX=1

# Braking rejection as in plot.sh (0 = off).
BRAKE_REJECT=0

# 1 = redraw the tables from the existing CSV, computing nothing.
PLOT_ONLY=0

# ==============================================================================

set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE/.."                      # repo root - the tools resolve sets from here
export MPLBACKEND=Agg
export BRAKE_REJECT WAVE_PARAM_FMAX

ARGS=(--session "$SESSION")
for c in "${COMBOS[@]}"; do
    ARGS+=(--combo "$c")
done
for t in "${TAPERS[@]}"; do
    read -r a b <<< "$t"
    ARGS+=(--taper "$a" "$b")
done
for c in "${PSD_COMPARE[@]}"; do
    ARGS+=(--psd-compare "$c")
done
for c in "${CHAIN_TABLE[@]}"; do
    ARGS+=(--chain-table "$c")
done
for x in "${CHAIN_FMAX[@]}"; do
    ARGS+=(--chain-fmax "$x")
done
for c in "${DECIMATION_TABLE[@]}"; do
    ARGS+=(--decimation-table "$c")
done
for x in "${FMAX_COMPARE[@]}"; do
    ARGS+=(--fmax-compare "$x")
done
if [[ -n $PSD_TAPER ]]; then
    read -r a b <<< "$PSD_TAPER"
    ARGS+=(--psd-taper "$a" "$b")
fi
if [[ $PLOT_ONLY == 1 ]]; then
    ARGS+=(--plot-only)
fi

python3 tools/script_test_config.py "$SET" "${ARGS[@]}"
