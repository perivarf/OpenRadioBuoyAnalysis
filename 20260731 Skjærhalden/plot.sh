#!/usr/bin/env bash
# Regenerate the figures for one measurement series. Run: ./plot.sh
#
# The series is a set in tools/analysis/session_sets.py, and every tool below is given the
# set NAME and reads sessions, directory, filename prefix and taper from it - so
# the figures cannot disagree with each other about which sessions belong to the
# series. What the set does not carry is in the settings block below.
#
# Every figure is computed from the session data with the CURRENT tools/ - the
# Kalman curves therefore come from the new filter (tools/filters/kalman.py, Kok
# et al.); the old one is kalman_prev.py. Figures that compare Madgwick and SFLP
# are unaffected; anything labelled "Kalman" will differ from earlier versions.
#
# Not produced here (Skjærhalden 2026-07-31):
#   *.jpg                 photos from the site, not figures
#   <stamp>_koherens.png  made by selfnoise.py, which is no longer in the repo
#
# Takes about 10 minutes for six sessions - most of it the AHRS replay.
#
# DO NOT EDIT THIS FILE WHILE IT RUNS: bash reads it as it goes, and an edit that
# shifts the lines makes it execute from the middle of a comment.

# ============================ settings ========================================

# Name of this run. EVERYTHING it produces goes under <measurement>/<CONFIG_NAME>/:
# the series figures there, and each session's figures, _ana_python.csv,
# _spec_python.csv and its inputs (imu.csv as a symlink) in <CONFIG_NAME>/<stamp>/. Every figure
# also gets _<CONFIG_NAME> in its name. Delete the directory to delete the run; the
# session directories themselves are only read.
#
# Required. Change it TOGETHER with MAP_TAPER - otherwise a new taper is written
# into the directory named after the old one.
CONFIG_NAME="0.03-0.05"

# The set in tools/analysis/session_sets.py. The figures are written under ITS directory,
# whichever directory this script happens to sit in.
SET=SKJAERHALDEN

# Taper for the maps, the overview table and _spec_acc/_spec_eta.png ("F1 F2" in Hz; F1 == F2 is
# a hard cut). It also sets Hs/Tz/Tc in _ana_python.csv. Empty = the set's own
# taper, which is what you normally want - set it only to try another band.
MAP_TAPER="0.03 0.05"

# Taper bands for the common elevation spectra - one _eta_madgwick_<f1>_<f2>.png
# per band. Not in the set on purpose: the sweep is there to show what the CHOICE
# of band does.
PSD_TAPERS=("0.03 0.05"      # Kohout/Tucker-Pitt
            "0.05 0.05"      # hard cut at Kohout's f2
            "0.05 0.1"       # ramp, as the Lillestrøm sets use
            "0.1 0.2"        # inshore - no swell below ~10 s
            "0.1 0.15"       # inshore, steeper ramp
            "0.03 0.03"      # hard cut
            "0.3 0.3")       # hard cut

# Sessions in the summary <prefix>_psd_rapport.png. Empty = every session in the
# set. Skjærhalden's report has always held just these two - one from each of the
# first two measurements.
REPORT_SESSIONS=(20260731_110303
                 20260731_122523)

# The 480 Hz sessions side by side in <prefix>_met_waves_480Hz_<C>.png, labelled
# with their names in the thesis.
MET_WAVES_SESSIONS=(20260731_110314 20260731_122652 20260731_131522)
MET_WAVES_LABELS=(1B 2B 3B)

# Buoy A (240 Hz) and B (480 Hz) per location, as pairs A B, for
# <prefix>_hs_ab_<C>.png: Hs per filter for both buoys and the difference B - A.
AB_PAIRS=(20260731_110303 20260731_110314
          20260731_122523 20260731_122652
          20260731_131527 20260731_131522)
AB_LABELS=(1 2 3)

# Sessions that also get <stamp>_psd_table_<C>.png: the spectrum of the single map
# on its own, titled with the measurement name. "all" = every session.
PSD_TABLE_SESSIONS="all"

# Reject a Welch segment when more than this fraction of its rows is flagged as
# braking (|linear accel| over brake_g_thresh in cfg.csv). 0 = off: in a short,
# steep sea the flag is set by the waves themselves and would reject nearly
# every segment. Empty = the default in tools/analysis/pipeline/settings.py.
BRAKE_REJECT=0

# 1 = redraw every figure from the numbers in data/ (written by the last normal
# run with this CONFIG_NAME), computing and fetching nothing - for labels, sizes
# and styles; takes seconds. 0 = the whole chain: compute -> data/ -> figures.
PLOT_ONLY=0

# ==============================================================================

set -euo pipefail
if [[ -z $CONFIG_NAME ]]; then
    echo "CONFIG_NAME is required - set it in the settings block of $0" >&2
    exit 2
fi
CONFIG=(--config "$CONFIG_NAME")   # the name itself is checked by the tools
PLOT_ARGS=()
if [[ $PLOT_ONLY == 1 ]]; then
    PLOT_ARGS=(--plot-only)        # every tool: draw from data/ only
fi
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE/.."                      # repo root - the tools resolve sets from here
export MPLBACKEND=Agg              # write files, open no windows
export BRAKE_REJECT                # read by tools/analysis/pipeline/settings.py

TAPER_ARGS=()
if [[ -n $MAP_TAPER ]]; then
    read -r F1 F2 <<< "$MAP_TAPER"
    TAPER_ARGS=(--taper "$F1" "$F2")      # same form as PSD_TAPERS below
fi

PSD_ARGS=()
for t in "${PSD_TAPERS[@]}"; do
    read -r a b <<< "$t"
    PSD_ARGS+=(--taper "$a" "$b")
done

REPORT_ARGS=()
if (( ${#REPORT_SESSIONS[@]} )); then
    REPORT_ARGS=(--sessions "${REPORT_SESSIONS[@]}")
fi

# Below, <C> is CONFIG_NAME: series figures land in <measurement>/<C>/, session
# figures in <measurement>/<C>/<stamp>/.
#
# Overview map + table, and per session <stamp>_map_<C>.png, _spec_acc_<C>.png and _spec_eta_<C>.png
# (postprocess runs first, writing _ana_python.csv/_spec_python.csv beside them).
# Writes <prefix>_overview_<C>.png, _map_<C>.png and _table_<C>.png - the overview
# was earlier called <prefix>_oversikt_kart.png.
# The measurement names on the maps (1A, 1B, ...) are the set's badge_nr.
python3 tools/script_plot.py "$SET" "${TAPER_ARGS[@]}" "${CONFIG[@]}" "${PLOT_ARGS[@]}" \
    --psd-table "$PSD_TABLE_SESSIONS"

# Common spectra, Madgwick, in <measurement>/taper_sweep/ (the same for every
# config): <prefix>_acc_madgwick.png (taper-free) and one
# <prefix>_eta_madgwick_<f1>_<f2>.png per band in PSD_TAPERS.
python3 tools/script_felles_psd.py "$SET" "${PSD_ARGS[@]}" "${CONFIG[@]}" "${PLOT_ARGS[@]}"

# Hs as a function of the low-frequency cutoff, also in taper_sweep/:
# <prefix>_hs_vs_fc_madgwick.png.
# Not affected by the tapers above - the cutoff is its x axis.
python3 tools/script_hs_cutoff.py "$SET" "${CONFIG[@]}" "${PLOT_ARGS[@]}"

# Untapered Madgwick/Kalman/GPS comparison: <stamp>_psd_utapert_<C>.png and
# <stamp>_psd_forhold_<C>.png for every session ...
python3 tools/script_psd_comp.py "$SET" "${CONFIG[@]}" "${PLOT_ARGS[@]}"

# ... and the summary <prefix>_psd_rapport_<C>.png.
python3 tools/script_psd_comp.py "$SET" "${REPORT_ARGS[@]}" "${CONFIG[@]}" "${PLOT_ARGS[@]}" \
    --only-report --report

# Modelled Hs (Kystvarslingssenteret) at each session's time and place,
# next to the IMU Hs/Tp from this run's _ana_python.csv: one table per session,
# <stamp>_met_waves_<C>.png, and <prefix>_met_waves_<C>.csv with one row per
# session. Downloads only what is not cached in
# ~/.cache/orb_met (the first run takes ~20 s per session).
python3 tools/script_met_waves.py "$SET" "${CONFIG[@]}" "${PLOT_ARGS[@]}"

# ... and the 480 Hz sessions in one table: <prefix>_met_waves_480Hz_<C>.png.
python3 tools/script_met_waves.py "$SET" "${CONFIG[@]}" "${PLOT_ARGS[@]}" \
    --sessions "${MET_WAVES_SESSIONS[@]}" --labels "${MET_WAVES_LABELS[@]}" --name 480Hz

# Hs per filter for buoy A and B at each location: <prefix>_hs_ab_<C>.png.
python3 tools/script_met_waves.py "$SET" "${CONFIG[@]}" "${PLOT_ARGS[@]}" \
    --ab "${AB_PAIRS[@]}" --ab-labels "${AB_LABELS[@]}"
